/** Minimal Code 128 encoder (subsets B and C, automatic switching). One Boolean per module (true = bar). */
object Code128 {
    private val T = arrayOf("11011001100","11001101100","11001100110","10010011000","10010001100","10001001100","10011001000","10011000100","10001100100","11001001000","11001000100","11000100100","10110011100","10011011100","10011001110","10111001100","10011101100","10011100110","11001110010","11001011100","11001001110","11011100100","11001110100","11101101110","11101001100","11100101100","11100100110","11101100100","11100110100","11100110010","11011011000","11011000110","11000110110","10100011000","10001011000","10001000110","10110001000","10001101000","10001100010","11010001000","11000101000","11000100010","10110111000","10110001110","10001101110","10111011000","10111000110","10001110110","11101110110","11010001110","11000101110","11011101000","11011100010","11011101110","11101011000","11101000110","11100010110","11101101000","11101100010","11100011010","11101111010","11001000010","11110001010","10100110000","10100001100","10010110000","10010000110","10000101100","10000100110","10110010000","10110000100","10011010000","10011000010","10000110100","10000110010","11000010010","11001010000","11110111010","11000010100","10001111010","10100111100","10010111100","10010011110","10111100100","10011110100","10011110010","11110100100","11110010100","11110010010","11011011110","11011110110","11110110110","10101111000","10100011110","10001011110","10111101000","10111100010","11110101000","11110100010","10111011110","10111101110","11101011110","11110101110","11010000100","11010010000","11010011100","1100011101011")

    fun modules(text: String): BooleanArray {
        val codes = ArrayList<Int>()
        val segs = ArrayList<Pair<Char, String>>()
        var i = 0
        val n = text.length
        val sb = StringBuilder()
        while (i < n) {
            var j = i
            while (j < n && text[j] in '0'..'9') j++
            val run = j - i
            val useC = run >= 4 && (i == 0 || run >= 6 || j == n)
            if (useC) {
                var s = i
                if (run % 2 == 1) { sb.append(text[s]); s++ }
                if (sb.isNotEmpty()) { segs.add('B' to sb.toString()); sb.setLength(0) }
                segs.add('C' to text.substring(s, j))
                i = j
            } else {
                val e = if (run > 0) j else i + 1
                sb.append(text, i, e)
                i = e
            }
        }
        if (sb.isNotEmpty()) segs.add('B' to sb.toString())
        var cur = ' '
        for ((k, seg) in segs) {
            if (k != cur) {
                codes.add(if (codes.isEmpty()) (if (k == 'C') 105 else 104) else (if (k == 'C') 99 else 100))
                cur = k
            }
            if (k == 'C') { var p = 0; while (p < seg.length) { codes.add(seg.substring(p, p + 2).toInt()); p += 2 } }
            else seg.forEach { codes.add(it.code - 32) }
        }
        var sum = codes[0]
        for (p in 1 until codes.size) sum += codes[p] * p
        codes.add(sum % 103)
        codes.add(106)
        val out = ArrayList<Boolean>()
        for (c in codes) T[c].forEach { out.add(it == '1') }
        return out.toBooleanArray()
    }
}
